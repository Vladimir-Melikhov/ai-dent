"""Сообщения протокола чата, общие для сервиса и агента (ТЗ §6.2)."""

ERROR_TEXTS = {
    "bad_request": "Не удалось обработать сообщение",
    "too_long": "Сообщение слишком длинное",
    "busy": "Консультант ещё отвечает — дождитесь ответа или нажмите «Остановить»",
    "rate_limited": "Слишком много сообщений подряд — подождите минуту",
    "limit_reached": "Консультант сейчас недоступен. Оставьте заявку — менеджер свяжется с вами",
    "conversation_full": "Диалог получился длинным — начните новый",
    "model_unavailable": "Консультант временно недоступен. Оставьте заявку — менеджер свяжется с вами",
    "refused": "На этот вопрос консультант ответить не может. Оставьте заявку — менеджер свяжется с вами",
}
# Ошибки, при которых клиенту показывается кнопка «Оставить заявку менеджеру»
LEAD_BUTTON_CODES = {"limit_reached", "model_unavailable", "refused"}


def error(code: str) -> dict:
    return {"type": "error", "code": code, "message": ERROR_TEXTS.get(code, ""),
            "show_lead_button": code in LEAD_BUTTON_CODES}

"""Маскирование ПДн в тексте клиента перед отправкой в модель.

Страховка, а не гарантия: ФИО и адрес в свободном тексте так не ловятся — поэтому агент
не спрашивает личные данные и направляет в форму. Порядок правил важен: сначала более
узкие форматы (email, карта, СНИЛС, телефон, паспорт), в конце — длинные числа.
"""

import re

SEP = r"[\s\-–—]*"

RULES = [
    ("[email]", re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")),
    # Номер карты: группы по четыре цифры через пробел или дефис, либо 16–19 цифр подряд
    # (13 и 15 цифр подряд — это ОГРН и ОГРНИП, они ниже)
    ("[номер карты]", re.compile(r"(?<!\d)(?:\d{4}([ \-])\d{4}\1\d{4}\1\d{1,7}|\d{16,19})(?!\d)")),
    # СНИЛС: 123-456-789 01
    ("[реквизит]", re.compile(r"(?<!\d)\d{3}-\d{3}-\d{3}[ \-]\d{2}(?!\d)")),
    # +7 / 8 / 7 и десять цифр в любом оформлении
    ("[телефон]", re.compile(
        rf"(?<![\d+])(?:\+7|8|7(?={SEP}\(?\d{{3}}))[\s\-–—(]*\d{{3}}[\s\-–—)]*\d{{3}}{SEP}\d{{2}}{SEP}\d{{2}}(?!\d)"
    )),
    # Мобильный без кода страны: 9XX XXX XX XX
    ("[телефон]", re.compile(rf"(?<!\d)9\d{{2}}{SEP}\d{{3}}{SEP}\d{{2}}{SEP}\d{{2}}(?!\d)")),
    # Паспорт: серия и номер через пробел — «4506 123456», «45 06 №123456»
    ("[документ]", re.compile(r"(?<!\d)\d{2}\s?\d{2}\s+№?\s?\d{6}(?!\d)")),
    # ИНН, ОГРН, ОГРНИП, СНИЛС без разделителей: 10–15 цифр подряд
    ("[реквизит]", re.compile(r"(?<!\d)\d{10,15}(?!\d)")),
]


def mask_pii(text: str) -> str:
    for replacement, pattern in RULES:
        text = pattern.sub(replacement, text)
    return text

"""Маскирование ПДн (ТЗ §7.6) и T18: артикулы, названия и цены не трогаются."""

import pytest

from app.ai.masking import mask_pii


@pytest.mark.parametrize("text, expected", [
    ("мой телефон +7 (999) 123-45-67", "мой телефон [телефон]"),
    ("8 999 123 45 67", "[телефон]"),
    ("89991234567", "[телефон]"),
    ("999-123-45-67", "[телефон]"),
    ("ivan.petrov@mail.ru", "[email]"),
    ("ИНН 7701234567", "ИНН [реквизит]"),
    ("ИНН 770123456789", "ИНН [реквизит]"),
    ("ОГРН 1027700132195", "ОГРН [реквизит]"),
    ("СНИЛС 123-456-789 01", "СНИЛС [реквизит]"),
    ("карта 4276 1234 5678 9012", "карта [номер карты]"),
    ("паспорт 4506 123456", "паспорт [документ]"),
])
def test_personal_data_is_masked(text, expected):
    assert mask_pii(text) == expected


@pytest.mark.parametrize("text", [
    # артикулы и модели из базы знаний и каталога
    "арт. 572-0012", "арт. 572-0050", "арт. 181331", "SLT 3.0 арт. 50M", "AM-2000 Plus", "EXTARO 300 Essential",
    "Prima DNT", "OPMI Pico dent Start Up", "Varioskop 230", "HL8200", "TC-View 2.5",
    # цены, размеры, даты
    "2 924 329 ₽", "1 983 000 ₽", "2924329 рублей", "до 500 тыс.", "106 233,82 ₽",
    "рабочая дистанция 420 мм, PD 62", "межзрачковое 50–75 мм", "поставка до 05.10.2026", "4–25×",
])
def test_catalog_texts_are_untouched(text):
    assert mask_pii(text) == text

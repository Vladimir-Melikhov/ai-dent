def test_knowledge_base_is_untouched_except_company_contacts():
    """База знаний — 68 КБ настоящего текста о стоматологии: ложных срабатываний быть не должно."""
    changed = [
        line for line in KB.splitlines()
        if line.strip() and mask_pii(line) != masking.normalize(line)
    ]
    # Меняются только строки с адресом и почтой компании — они и есть адрес и почта
    assert changed and all("ул. Волочаевская" in line for line in changed)


def test_brand_vocabulary_by_sound():
    """Бренд кириллицей защищён по звучанию, но слово, которое скорее имя, не прикрывает."""
    vocabulary = masking.Vocabulary(["Zumax", "I.C. Lercher", "Heine Optotechnik", "Sony", "KLS Martin"])
    for word in ("Зумакс", "Зумакса", "Лерхер", "Лерхера", "Хайне", "Zumax", "Lercher"):
        assert vocabulary.protects(word), word
    for word in ("Соня", "Мартин", "Иван", "Зайцев"):
        assert not vocabulary.protects(word), word


def test_masking_is_idempotent_and_placeholders_survive():
    for text, _ in [*_cases(test_patterns), *_cases(test_context), *_cases(test_names)]:
        once = mask_pii(text)
        assert mask_pii(once) == once, text
    assert mask_pii("Звоните [телефон], [имя], адрес: [адрес]") == "Звоните [телефон], [имя], адрес: [адрес]"


def _cases(test):
    return next(m.args[1] for m in test.pytestmark if m.name == "parametrize")


